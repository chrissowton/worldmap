// Writes DATA.md: a table of every measure on the site, with its source, year and coverage.
// Run after build_data.py:   node make_data_table.cjs
const fs = require("fs");
global.window = {};
eval(fs.readFileSync(__dirname + "/filters.js", "utf8"));
const { FILTERS, FILTER_GROUPS, SOURCES } = window;
const rows = JSON.parse(fs.readFileSync(__dirname + "/countries.json", "utf8")).filter((r) => r.sovereign);
const cities = JSON.parse(fs.readFileSync(__dirname + "/cities.json", "utf8"));
const ts = JSON.parse(fs.readFileSync(__dirname + "/timeseries.json", "utf8"));
function yearly(f) {
  const s = ts.series[f.key === "democracy" ? "regime" : f.key];
  if (!s) return "–";
  let first = Infinity;
  for (const arr of Object.values(s)) { const i = arr.findIndex((v) => v != null); if (i >= 0) first = Math.min(first, i); }
  return `from ${ts.years[first]}`;
}

function year(f) {
  if (f.yearText) return f.yearText;
  if (typeof f.year === "number") return String(f.year);
  if (!f.year) return "–";
  const ys = rows.map((r) => r[f.year]).filter((y) => typeof y === "number");
  if (!ys.length) return "–";
  const lo = Math.min(...ys), hi = Math.max(...ys);
  const counts = {};
  ys.forEach((y) => (counts[y] = (counts[y] || 0) + 1));
  const mode = Object.entries(counts).sort((a, b) => b[1] - a[1])[0][0];
  return lo === hi ? String(hi) : `mostly ${mode} (${lo}–${hi})`;
}
function coverage(f) {
  if (f.target === "city") return `${cities.length.toLocaleString("en-GB")} cities`;
  const n = rows.filter((r) => {
    const v = r[f.key];
    return Array.isArray(v) ? v.length > 0 : v !== undefined && v !== null && v !== "";
  }).length;
  return `${n} of ${rows.length}`;
}

let md = `# Data on the site

Every measure you can filter by, where it comes from and how up to date it is.
"Coverage" counts the ${rows.length} countries (sovereign states) that have a value. "Year slider" shows which measures have yearly data you can go back through.
This file is generated by \`make_data_table.cjs\`; edit \`filters.js\` and rerun it rather than editing this file.

`;
for (const g of FILTER_GROUPS) {
  const fs_ = FILTERS.filter((f) => f.group === g);
  if (!fs_.length) continue;
  md += `## ${g}\n\n| Measure | What it shows | Source | Year | Coverage | Year slider |\n|---|---|---|---|---|---|\n`;
  for (const f of fs_) {
    const s = SOURCES[f.source];
    md += `| ${f.label} | ${f.info.replace(/\|/g, "/")} | [${s.name}](${s.url}) | ${year(f)} | ${coverage(f)} | ${yearly(f)} |\n`;
  }
  md += "\n";
}
md += `## Sources and licences

| Source | Licence |
|---|---|
${Object.values(SOURCES).map((s) => `| [${s.name}](${s.url}) | ${s.licence} |`).join("\n")}
`;
fs.writeFileSync(__dirname + "/DATA.md", md);
console.log("Wrote DATA.md");
